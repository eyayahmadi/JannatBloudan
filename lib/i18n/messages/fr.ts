// Widen les littéraux (chaque chaîne devient `string`) afin que les autres
// locales (en/de/ar) puissent fournir leurs propres traductions sans que
// TypeScript les rejette parce qu'elles ne correspondent pas au texte français.
type DeepWiden<T> = T extends string
  ? string
  : T extends readonly unknown[]
  ? { [K in keyof T]: DeepWiden<T[K]> }
  : T extends object
  ? { [K in keyof T]: DeepWiden<T[K]> }
  : T

export type Messages = DeepWiden<typeof fr>
