#!/usr/bin/env node
/**
 * Full menu integrity audit vs printed source (data/jannat-bloudan-menu.json).
 *
 * Usage: node --env-file=.env.local scripts/audit-menu-integrity.mjs
 */
import pg from "pg"
import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const menu = JSON.parse(fs.readFileSync(path.join(__dirname, "../data/jannat-bloudan-menu.json"), "utf8"))
const bySlug = new Map(menu.products.map((p) => [p.slug, p]))
const recMap = menu.productRecommendations ?? {}

const HTML_RE = /<\/?[a-z][^>]*>/i
const GARBAGE_RE =
  /His heart began|The amount that has been paid|Emoji Cheat Sheet|cheat sheet|lorem ipsum|ChatGPT|generated by AI|<svg|<xml/i

/** Active categories in canonical order (excludes inactive tea). */
const EXPECTED_CATEGORIES = menu.categories
  .filter((c) => c.is_active !== false)
  .sort((a, b) => a.display_order - b.display_order)

function tagsKey(tags) {
  const arr = Array.isArray(tags) ? [...tags] : JSON.parse(tags || "[]")
  return [...new Set(arr)].sort().join(",")
}

function expectedTags(p) {
  const tags = [...(p.tags ?? [])]
  if (p.is_popular && !tags.includes("popular")) tags.push("popular")
  if (p.is_chef_choice && !tags.includes("chef_recommendation")) tags.push("chef_recommendation")
  return [...new Set(tags)].sort().join(",")
}

function expectedImagePath(p) {
  const folder = p.imageCategory ?? p.category
  return `products/${folder}/${p.slug}.webp`
}

const dbUrl = process.env.DATABASE_URL ?? ""
const useSsl =
  process.env.PGSSLMODE === "require" ||
  (dbUrl.includes("supabase.co") && process.env.PGSSLMODE !== "disable")
const db = new pg.Client({
  connectionString: dbUrl,
  ...(useSsl ? { ssl: { rejectUnauthorized: false } } : {}),
})
await db.connect()

const { rows: categories } = await db.query(`
  SELECT slug, name, name_ar, display_order, is_active, section
  FROM categories
  ORDER BY display_order, slug
`)

const { rows: products } = await db.query(`
  SELECT p.id, p.slug, p.name, p.name_ar, p.description, p.description_ar,
    p.price, p.image_url, p.tags, p.station, p.display_order,
    c.slug AS category_slug
  FROM products p
  LEFT JOIN categories c ON c.id = p.category_id
  ORDER BY c.display_order, p.display_order, p.slug
`)

const { rows: recRows } = await db.query(`
  SELECT p.slug AS product_slug, rp.slug AS rec_slug, pr.display_order
  FROM product_recommendations pr
  JOIN products p ON p.id = pr.product_id
  JOIN products rp ON rp.id = pr.recommended_product_id
  ORDER BY p.slug, pr.display_order
`)

const counts = {
  wrong_names: 0,
  wrong_name_ar: 0,
  wrong_descriptions: 0,
  wrong_description_ar: 0,
  wrong_images: 0,
  wrong_categories: 0,
  wrong_category_order: 0,
  wrong_product_order: 0,
  cross_category_products: 0,
  wrong_prices: 0,
  wrong_tags: 0,
  wrong_recommendations: 0,
  placeholder_text: 0,
  html_fragments: 0,
  broken_images: 0,
  english_placeholders: 0,
  menu_mismatch: 0,
  missing_products: 0,
  extra_products: 0,
}

const details = []

function bump(key, msg) {
  counts[key]++
  details.push(msg)
}

// Category order audit (active categories only)
const activeDbCats = categories.filter((c) => c.is_active !== false)
for (let i = 0; i < EXPECTED_CATEGORIES.length; i++) {
  const exp = EXPECTED_CATEGORIES[i]
  const dbCat = activeDbCats[i]
  if (!dbCat || dbCat.slug !== exp.slug) {
    bump("wrong_category_order", `position ${i + 1}: expected ${exp.slug}, got ${dbCat?.slug ?? "none"}`)
  } else if (Number(dbCat.display_order) !== Number(exp.display_order)) {
    bump("wrong_category_order", `${exp.slug}: display_order ${dbCat.display_order} != ${exp.display_order}`)
  }
}

// Products per category in expected order
const expectedByCat = new Map()
for (const p of menu.products) {
  if (!expectedByCat.has(p.category)) expectedByCat.set(p.category, [])
  expectedByCat.get(p.category).push(p)
}
for (const [, list] of expectedByCat) {
  list.sort((a, b) => (a.display_order ?? 0) - (b.display_order ?? 0))
}

const dbByCat = new Map()
for (const p of products) {
  if (!dbByCat.has(p.category_slug)) dbByCat.set(p.category_slug, [])
  dbByCat.get(p.category_slug).push(p)
}

for (const [catSlug, expList] of expectedByCat) {
  const dbList = (dbByCat.get(catSlug) ?? []).sort(
    (a, b) => a.display_order - b.display_order || a.slug.localeCompare(b.slug)
  )
  for (let i = 0; i < expList.length; i++) {
    const exp = expList[i]
    const dbp = dbList[i]
    if (!dbp || dbp.slug !== exp.slug) {
      bump("wrong_product_order", `${catSlug} pos ${i + 1}: expected ${exp.slug}, got ${dbp?.slug ?? "none"}`)
    } else if (Number(dbp.display_order) !== Number(exp.display_order ?? 0)) {
      bump("wrong_product_order", `${exp.slug}: display_order ${dbp.display_order} != ${exp.display_order}`)
    }
  }
}

// Cross-category: product slug prefix vs category
const CATEGORY_PREFIX = {
  entrees: null,
  salades: null,
  manakish: (s) => s.startsWith("manakish-"),
  plats: null,
  shawarma: (s) => s.includes("shawarma"),
  grillades: null,
  pizza: (s) => s.startsWith("pizza-"),
  burgers: (s) => s.includes("burger"),
  sandwiches: null,
  water: null,
  juices: (s) => s.includes("saft") || s.includes("juice") || s.includes("kiba"),
  "soft-drinks": null,
  "ice-tea": (s) => s.startsWith("eistee-"),
  cocktails: (s) => s.includes("mojito") || s.includes("cocktail") || s.includes("ipanema") || s.includes("jamaica") || s.includes("maracuja") || s.includes("ananas"),
  smoothies: (s) => s.includes("smoothie"),
  milkshakes: (s) => s.includes("milkshake"),
  "banana-milk-cocktails": (s) => s.startsWith("banane-milch-"),
  coffee: null,
  "iced-coffee": (s) => s.startsWith("iced-") || s === "frappuccino",
  waffeln: (s) => s.includes("waffle"),
  crepes: (s) => s.includes("crepe"),
  pancakes: (s) => s.includes("pancake"),
  "fruit-salads": (s) => s.startsWith("fruit-salad-"),
  snacks: null,
  "ice-cream": (s) => s.startsWith("eis-") || s === "coupe-arabe",
  cheesecakes: (s) => s.startsWith("cheesecake-"),
  cakes: (s) => s.includes("cake") || s.includes("brownie"),
  shisha: (s) => s.startsWith("shisha-"),
  imperator: (s) => s.startsWith("imperator-"),
}

for (const exp of menu.products) {
  const rule = CATEGORY_PREFIX[exp.category]
  if (rule && !rule(exp.slug)) {
    bump("cross_category_products", `${exp.slug} may not belong in ${exp.category}`)
  }
}

const canonicalDesc = new Map()
for (const p of menu.products) {
  const d = (p.description || "").trim()
  if (d) canonicalDesc.set(d, p.slug)
}

for (const exp of menu.products) {
  const dbp = products.find((r) => r.slug === exp.slug)
  if (!dbp) {
    bump("missing_products", `missing: ${exp.slug}`)
    counts.menu_mismatch++
    continue
  }

  const fields = [dbp.name, dbp.name_ar, dbp.description, dbp.description_ar].join(" ")
  if (HTML_RE.test(fields)) bump("html_fragments", `html in ${exp.slug}`)
  if (GARBAGE_RE.test(fields)) bump("placeholder_text", `garbage text in ${exp.slug}`)

  if (dbp.name !== exp.name) bump("wrong_names", `${exp.slug}: "${dbp.name}" != "${exp.name}"`)
  if ((dbp.name_ar || "") !== (exp.name_ar || ""))
    bump("wrong_name_ar", `${exp.slug}: name_ar mismatch`)

  if ((dbp.description || "").trim() !== (exp.description || "").trim())
    bump("wrong_descriptions", `${exp.slug}`)

  const expAr = exp.description_ar ? exp.description_ar.trim() : null
  const dbAr = dbp.description_ar ? dbp.description_ar.trim() : null
  if (expAr !== dbAr && (expAr || dbAr)) {
    if (expAr && dbAr !== expAr) bump("wrong_description_ar", `${exp.slug}`)
    if (!expAr && dbAr) bump("wrong_description_ar", `${exp.slug}: unexpected AR text`)
  }

  if (dbp.category_slug !== exp.category) {
    bump("wrong_categories", `${exp.slug}: ${dbp.category_slug} != ${exp.category}`)
    counts.menu_mismatch++
  }
  if (Number(dbp.price) !== Number(exp.price)) bump("wrong_prices", `${exp.slug}`)

  const img = String(dbp.image_url || "")
  const need = expectedImagePath(exp)
  if (!img.includes(need)) {
    bump("wrong_images", `${exp.slug}: ${img}`)
    bump("broken_images", `${exp.slug}: path mismatch`)
  } else if (!img.startsWith("http")) {
    bump("broken_images", `${exp.slug}: missing absolute URL`)
  }

  if (tagsKey(dbp.tags) !== expectedTags(exp)) bump("wrong_tags", `${exp.slug}`)

  const dbDesc = (dbp.description || "").trim()
  if (dbDesc) {
    const owner = canonicalDesc.get(dbDesc)
    if (owner && owner !== exp.slug) {
      bump("cross_category_products", `${exp.slug} has description of ${owner}`)
    }
  }
}

for (const dbp of products) {
  if (!bySlug.has(dbp.slug)) bump("extra_products", dbp.slug)
}

const recByProduct = new Map()
for (const r of recRows) {
  if (!recByProduct.has(r.product_slug)) recByProduct.set(r.product_slug, [])
  recByProduct.get(r.product_slug).push(r.rec_slug)
}

for (const [slug, expectedRecs] of Object.entries(recMap)) {
  const actual = recByProduct.get(slug) ?? []
  const exp = [...expectedRecs]
  if (actual.join("|") !== exp.join("|")) {
    bump("wrong_recommendations", `${slug}: [${actual.join(",")}] != [${exp.join(",")}]`)
  }
  recByProduct.delete(slug)
}

for (const [slug, actual] of recByProduct) {
  if (actual.length > 0) bump("wrong_recommendations", `${slug}: extra recs [${actual.join(",")}]`)
}

console.log("\n📋 Menu integrity audit (printed source: jannat-bloudan-menu.json)\n")
console.log(`Products in DB: ${products.length} | Expected: ${menu.products.length}\n`)
console.log(`wrong_names: ${counts.wrong_names}`)
console.log(`wrong_name_ar: ${counts.wrong_name_ar}`)
console.log(`wrong_descriptions: ${counts.wrong_descriptions}`)
console.log(`wrong_description_ar: ${counts.wrong_description_ar}`)
console.log(`wrong_images: ${counts.wrong_images}`)
console.log(`wrong_categories: ${counts.wrong_categories}`)
console.log(`wrong_category_order: ${counts.wrong_category_order}`)
console.log(`wrong_product_order: ${counts.wrong_product_order}`)
console.log(`cross_category_products: ${counts.cross_category_products}`)
console.log(`wrong_prices: ${counts.wrong_prices}`)
console.log(`wrong_tags: ${counts.wrong_tags}`)
console.log(`wrong_recommendations: ${counts.wrong_recommendations}`)
console.log(`placeholder_text: ${counts.placeholder_text}`)
console.log(`html_fragments: ${counts.html_fragments}`)
console.log(`broken_images: ${counts.broken_images}`)
console.log(`english_placeholders: ${counts.english_placeholders}`)
console.log(`menu_mismatch: ${counts.menu_mismatch}`)
console.log(`missing products: ${counts.missing_products}`)
console.log(`extra products: ${counts.extra_products}`)

if (details.length) {
  console.log("\n--- Details (first 40) ---")
  details.slice(0, 40).forEach((d) => console.log(" ", d))
  if (details.length > 40) console.log(`  … and ${details.length - 40} more`)
}

const failKeys = [
  "wrong_names",
  "wrong_name_ar",
  "wrong_descriptions",
  "wrong_description_ar",
  "wrong_images",
  "wrong_categories",
  "wrong_category_order",
  "wrong_product_order",
  "cross_category_products",
  "wrong_prices",
  "placeholder_text",
  "html_fragments",
  "broken_images",
  "menu_mismatch",
  "missing_products",
  "extra_products",
]

const fail = failKeys.reduce((n, k) => n + counts[k], 0)

await db.end()
process.exit(fail > 0 ? 1 : 0)
