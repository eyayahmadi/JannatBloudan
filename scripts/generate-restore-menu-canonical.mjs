#!/usr/bin/env node
/**
 * Generates scripts/56-restore-menu-canonical.sql from data/jannat-bloudan-menu.json
 * Restores printed-menu text only — overwrites generated content from migrations 39–53.
 *
 * Usage: node scripts/generate-restore-menu-canonical.mjs
 */
import { readFileSync, writeFileSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, "..")
const menu = JSON.parse(readFileSync(join(ROOT, "data/jannat-bloudan-menu.json"), "utf8"))

function esc(s) {
  return String(s ?? "").replace(/'/g, "''")
}

function tagsJson(p) {
  const tags = [...(p.tags ?? [])]
  if (p.is_popular && !tags.includes("popular")) tags.push("popular")
  if (p.is_chef_choice && !tags.includes("chef_recommendation")) tags.push("chef_recommendation")
  return JSON.stringify([...new Set(tags)])
}

function legacyFromTags(tags) {
  const set = new Set(tags ?? [])
  return {
    is_popular: set.has("popular") || set.has("best_seller"),
    is_vegetarian: set.has("vegetarian"),
    is_vegan: set.has("vegan"),
    is_chef_choice: set.has("chef_recommendation"),
    is_recommended: set.has("chef_recommendation"),
    is_halal: set.has("halal"),
  }
}

const lines = []
lines.push(`-- =============================================================================
-- 56 — Restore menu from printed source (data/jannat-bloudan-menu.json)
-- Generated by scripts/generate-restore-menu-canonical.mjs — do not edit by hand
-- Overwrites AI/generated content from migrations 39–53. Does NOT touch image_url.
-- =============================================================================

BEGIN;

DO $$
DECLARE
  cat_entrees UUID; cat_salades UUID; cat_manakish UUID; cat_plats UUID;
  cat_shawarma UUID; cat_grillades UUID; cat_pizza UUID; cat_burgers UUID;
  cat_sandwiches UUID; cat_water UUID; cat_juices UUID; cat_soft_drinks UUID;
  cat_ice_tea UUID; cat_tea UUID; cat_iced_coffee UUID; cat_coffee UUID;
  cat_cocktails UUID; cat_smoothies UUID; cat_milkshakes UUID;
  cat_banana_milk_cocktails UUID; cat_imperator UUID; cat_waffeln UUID;
  cat_crepes UUID; cat_pancakes UUID; cat_fruit_salads UUID; cat_snacks UUID;
  cat_ice_cream UUID; cat_cheesecakes UUID; cat_cakes UUID; cat_shisha UUID;
  pid UUID; rid UUID; rec_slug TEXT; rec_slugs TEXT[]; ord INT;
BEGIN`)

for (const c of menu.categories) {
  const v = c.slug.replace(/-/g, "_")
  lines.push(`  SELECT id INTO cat_${v} FROM categories WHERE slug = '${esc(c.slug)}';`)
}

lines.push(`
  -- Category names, Arabic labels, and display order (29-category canonical layout)
  UPDATE categories c SET
    name = o.name,
    name_ar = o.name_ar,
    section = o.section,
    display_order = o.display_order,
    is_active = COALESCE(o.is_active, true)
  FROM (VALUES`)
const catValues = menu.categories.map((c) => {
  const active = c.is_active === false ? "false" : "true"
  return `    ('${esc(c.slug)}', '${esc(c.name)}', '${esc(c.name_ar)}', '${esc(c.section)}', ${c.display_order}, ${active})`
})
lines.push(catValues.join(",\n"))
lines.push(`  ) AS o(slug, name, name_ar, section, display_order, is_active)
  WHERE c.slug = o.slug;`)

for (const p of menu.products) {
  const catVar = p.category.replace(/-/g, "_")
  const tagList = JSON.parse(tagsJson(p))
  const legacy = legacyFromTags(tagList)
  const descAr = p.description_ar ? `'${esc(p.description_ar)}'` : "NULL"
  const spice = p.spice_level
    ? `'${esc(p.spice_level)}'`
    : tagList.includes("spicy")
      ? "'épicé'"
      : "NULL"

  lines.push(`
  UPDATE products SET
    name = '${esc(p.name)}',
    name_ar = '${esc(p.name_ar)}',
    description = '${esc(p.description ?? p.name)}',
    description_ar = ${descAr},
    price = ${p.price},
    category_id = cat_${catVar},
    display_order = ${p.display_order ?? 0},
    station = '${esc(p.station)}',
    tags = '${esc(tagsJson(p))}'::jsonb,
    is_popular = ${legacy.is_popular},
    is_vegetarian = ${legacy.is_vegetarian},
    is_vegan = ${legacy.is_vegan},
    is_chef_choice = ${legacy.is_chef_choice},
    is_recommended = ${legacy.is_recommended},
    is_halal = ${legacy.is_halal ?? true},
    spice_level = ${spice}
  WHERE slug = '${esc(p.slug)}';`)
}

lines.push(`
  -- Recommendations from printed menu source only (productRecommendations in JSON)
  DELETE FROM product_recommendations;`)

const recs = menu.productRecommendations ?? {}
for (const [productSlug, recSlugs] of Object.entries(recs)) {
  if (!Array.isArray(recSlugs) || recSlugs.length === 0) continue
  const arr = recSlugs.map((s) => `'${esc(s)}'`).join(", ")
  lines.push(`
  rec_slugs := ARRAY[${arr}];
  SELECT id INTO pid FROM products WHERE slug = '${esc(productSlug)}';
  IF pid IS NOT NULL THEN
    ord := 0;
    FOREACH rec_slug IN ARRAY rec_slugs LOOP
      SELECT id INTO rid FROM products WHERE slug = rec_slug;
      IF rid IS NOT NULL AND rid <> pid THEN
        INSERT INTO product_recommendations (product_id, recommended_product_id, display_order)
        VALUES (pid, rid, ord)
        ON CONFLICT (product_id, recommended_product_id) DO NOTHING;
        ord := ord + 1;
      END IF;
    END LOOP;
  END IF;`)
}

lines.push(`
END $$;

COMMIT;
`)

const outPath = join(__dirname, "56-restore-menu-canonical.sql")
writeFileSync(outPath, lines.join("\n"), "utf8")
console.log(`Wrote ${outPath} (${menu.products.length} products, ${Object.keys(recs).length} recommendation sets)`)
